// 한 번 실행하면 브리지를 쓸 수 있게 해 주는 설치 파일을 페이지에서 바로 만들어 내려준다.
// (서버가 없어도 되도록 앱/브리지 주소를 파일 안에 박아 넣는다)

/** Windows: 더블클릭용 .cmd. 이미 된 단계는 건너뛰므로 여러 번 실행해도 된다. */
export function windowsSetup(appUrl: string, bridgeUrl: string): string {
  const safe = (s: string) => s.replace(/[%"&|<>^]/g, '');
  const lines = [
    '@echo off',
    'chcp 65001 >nul',
    'setlocal',
    'title Tail Cards 브리지 설치',
    `set "APP=${safe(appUrl)}"`,
    `set "BRIDGE_URL=${safe(bridgeUrl)}"`,
    'set "DIR=%LOCALAPPDATA%\\TailCards"',
    'set "STARTUP=%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup\\Tail Cards Bridge.cmd"',
    'set "PATH=%ProgramFiles%\\nodejs;%APPDATA%\\npm;%PATH%"',
    'echo.',
    'echo  Tail Cards 브리지 설치 - 이미 된 단계는 건너뜁니다',
    'echo.',
    '',
    'echo [1/5] Node.js 확인',
    'where node >nul 2>nul && goto node_ok',
    'echo      Node.js를 설치합니다 - winget, 권한 확인 창이 뜨면 허용',
    'winget install --id OpenJS.NodeJS.LTS -e --silent --accept-source-agreements --accept-package-agreements',
    'where node >nul 2>nul || goto fail_node',
    ':node_ok',
    '',
    'echo [2/5] Claude Code 확인',
    'if exist "%APPDATA%\\npm\\claude.cmd" goto claude_ok',
    'echo      Claude Code를 설치합니다 - 1~2분',
    'call npm.cmd install -g @anthropic-ai/claude-code --no-fund --no-audit',
    'if not exist "%APPDATA%\\npm\\claude.cmd" goto fail_claude',
    ':claude_ok',
    '',
    'echo [3/5] Claude 로그인 확인',
    'call "%APPDATA%\\npm\\claude.cmd" auth status | findstr /r /c:"loggedIn.: true" >nul && goto login_ok',
    'echo      브라우저가 열리면 Claude 구독 계정으로 로그인하세요.',
    'echo      코드를 붙여넣으라고 나오면 브라우저에 표시된 코드를 여기에 붙여넣고 Enter',
    'call "%APPDATA%\\npm\\claude.cmd" auth login --claudeai',
    'call "%APPDATA%\\npm\\claude.cmd" auth status | findstr /r /c:"loggedIn.: true" >nul || goto fail_login',
    ':login_ok',
    '',
    'echo [4/5] 브리지 내려받기',
    'if not exist "%DIR%" mkdir "%DIR%"',
    'curl.exe -fsSL "%BRIDGE_URL%" -o "%DIR%\\tail-cards-bridge.mjs" || goto fail_download',
    '',
    'echo [5/5] 로그인할 때 자동 실행 등록 + 지금 시작',
    'for /f "delims=" %%n in (\'where node\') do (set "NODE=%%n" & goto got_node)',
    ':got_node',
    '> "%STARTUP%" echo @start "Tail Cards Bridge" /min "%NODE%" "%DIR%\\tail-cards-bridge.mjs" --app "%APP%"',
    'start "Tail Cards Bridge" /min "%NODE%" "%DIR%\\tail-cards-bridge.mjs" --app "%APP%"',
    'echo.',
    'echo  완료! 페이지로 돌아가면 자동으로 연결됩니다.',
    'echo  브리지는 작업 표시줄의 최소화된 창으로 실행되고, 다음부터는 Windows 로그인 때 자동으로 켜집니다.',
    'echo  제거: 시작 프로그램의 "Tail Cards Bridge.cmd" 와 %DIR% 폴더를 지우면 됩니다.',
    'echo.',
    'start "" "%APP%#/generate"',
    'timeout /t 8',
    'exit /b 0',
    '',
    ':fail_node',
    'echo  Node.js 설치에 실패했습니다. https://nodejs.org 에서 LTS를 설치한 뒤 이 파일을 다시 실행하세요.',
    'goto end_fail',
    ':fail_claude',
    'echo  Claude Code 설치에 실패했습니다. 위의 오류를 확인한 뒤 다시 실행하세요.',
    'goto end_fail',
    ':fail_login',
    'echo  로그인이 완료되지 않았습니다. 이 파일을 다시 실행해 로그인해 주세요.',
    'goto end_fail',
    ':fail_download',
    'echo  브리지를 내려받지 못했습니다: %BRIDGE_URL%',
    ':end_fail',
    'echo.',
    'pause',
    'exit /b 1',
  ];
  return lines.join('\r\n') + '\r\n';
}

/** macOS·Linux: 터미널에서 `bash tail-cards-setup.sh` */
export function unixSetup(appUrl: string, bridgeUrl: string): string {
  const q = (s: string) => `'${s.replace(/'/g, '')}'`;
  return [
    '#!/usr/bin/env bash',
    'set -e',
    `APP=${q(appUrl)}`,
    `BRIDGE_URL=${q(bridgeUrl)}`,
    'DIR="$HOME/.tail-cards"',
    'echo "[1/4] Node.js 확인"',
    'command -v node >/dev/null || { echo "Node.js가 필요합니다: https://nodejs.org (macOS는 brew install node)"; exit 1; }',
    'echo "[2/4] Claude Code 확인"',
    'command -v claude >/dev/null || npm install -g @anthropic-ai/claude-code',
    'echo "[3/4] Claude 로그인 확인"',
    'claude auth status | grep -q \'"loggedIn": true\' || claude auth login --claudeai',
    'echo "[4/4] 브리지 내려받고 시작"',
    'mkdir -p "$DIR"',
    'curl -fsSL "$BRIDGE_URL" -o "$DIR/tail-cards-bridge.mjs"',
    'nohup node "$DIR/tail-cards-bridge.mjs" --app "$APP" > "$DIR/bridge.log" 2>&1 &',
    'echo "완료! 페이지로 돌아가면 자동으로 연결됩니다. (로그: $DIR/bridge.log)"',
    'echo "다음에 다시 켤 때: node \\"$DIR/tail-cards-bridge.mjs\\" --app \\"$APP\\""',
    '(command -v open >/dev/null && open "${APP}#/generate") || (command -v xdg-open >/dev/null && xdg-open "${APP}#/generate") || true',
    '',
  ].join('\n');
}
